"""Pre-submission check for Data Project 3. Run it from the project3 folder:

  python kit/check_project.py

It prints READY, or a list of what is still missing. It checks the things the
grader checks first; it does not judge the quality of your code or analysis.
Do not edit this file.
"""
import glob
import os
import re
import subprocess
import sys

TARGET = 50_000
MAX_SAMPLE_MB = 5
README_HEADINGS = [
    "Data source", "How to run", "Architecture", "Design decisions", "Chaos round",
    "The four numbers", "Challenges", "Analysis", "Plot", "Reflection", "Acknowledgements",
]
SESSIONS = ["Thu 05 Nov", "Mon 09 Nov", "Thu 12 Nov", "Mon 16 Nov"]

problems, warnings, ok = [], [], []


def read(path):
    try:
        with open(path, encoding="utf8") as f:
            return f.read()
    except OSError:
        return None


def git(*args):
    try:
        out = subprocess.run(["git", *args], capture_output=True, text=True, timeout=30)
        return out.stdout if out.returncode == 0 else None
    except (OSError, subprocess.SubprocessError):
        return None


# 0. Where am I?
if not os.path.exists("SOURCE_CARD.md") or not os.path.isdir("kit"):
    sys.exit("Run this from your project3 folder:  cd project3  then  python kit/check_project.py")

# 1. Volume: raw records landed (local files, not in git)
raw_files = glob.glob("data/raw/*.parquet")
if not raw_files:
    problems.append("No raw landing files in data/raw/ on this laptop (checkpoint C).")
else:
    try:
        import duckdb
        n = duckdb.connect().execute("SELECT count(*) FROM read_parquet('data/raw/*.parquet')").fetchone()[0]
        line = f"{n:,} raw records landed in {len(raw_files)} files (target {TARGET:,})"
        (ok if n >= TARGET else problems).append(line)
    except Exception as e:  # noqa: BLE001
        problems.append(f"Could not read data/raw/*.parquet: {e}")

# 2. Sample for the grader and the peer test
sample = glob.glob("data/sample/*.parquet")
if not sample:
    problems.append("No data/sample/*.parquet. Run: python kit/make_sample.py")
else:
    mb = sum(os.path.getsize(f) for f in sample) / 1e6
    (ok if mb <= MAX_SAMPLE_MB else problems).append(f"data/sample/ is {mb:.2f} MB (max {MAX_SAMPLE_MB} MB)")

# 3. The project files exist and are filled in
for f in ["producer.py", "lander.py", "flow.py"]:
    (ok if os.path.exists(f) else problems).append(f"{f} {'present' if os.path.exists(f) else 'missing'}")

card = read("SOURCE_CARD.md") or ""
m = re.search(r"##\s*7\.[^\n]*\n(.*)", card, re.S)
boxes = re.findall(r"^- \[( |x|X)\]", m.group(1), re.M) if m else []
ticked = sum(1 for b in boxes if b.lower() == "x")
if boxes and ticked == len(boxes):
    ok.append(f"Source Design Card self-check: {ticked} of {len(boxes)} ticked")
else:
    warnings.append(f"SOURCE_CARD.md self-check: {ticked} of {len(boxes) or 7} boxes ticked (section 7)")

readme = read("README.md") or ""
missing = [h for h in README_HEADINGS if not re.search(rf"^#+\s*{re.escape(h)}", readme, re.I | re.M)]
if missing:
    problems.append("README.md is missing headings: " + ", ".join(missing))
else:
    ok.append("README.md has all required headings")
left = len(re.findall(r"\bTODO\b|_\(replace", readme))
if left:
    problems.append(f"README.md still has {left} TODO / '(replace' placeholders")
images = re.findall(r"!\[[^\]]*\]\(([^)]+)\)", readme)
broken = [i for i in images if not i.startswith("http") and not os.path.exists(i)]
if not images:
    problems.append("README.md shows no chart (use ![title](charts/your_chart.png))")
elif broken:
    problems.append("README.md links images that do not exist: " + ", ".join(broken))
else:
    ok.append(f"README.md shows {len(images)} image(s)")

docs = [f for f in glob.glob("docs/*") if f.lower().endswith((".png", ".jpg", ".jpeg", ".gif"))]
(ok if len(docs) >= 3 else problems).append(
    f"{len(docs)} screenshot(s) in docs/ (need 3: Console topic, flow log with the four numbers, Prefect dashboard)")

progress = read("PROGRESS.md") or ""
empty = []
for s in SESSIONS:
    m = re.search(rf"##[^\n]*{s}[^\n]*\n(.*?)(?=\n## |\Z)", progress, re.S)
    if not m or not re.search(r"Done:[ \t]*\S", m.group(1)):
        empty.append(s)
if empty:
    warnings.append("PROGRESS.md has no 'Done:' entry for: " + ", ".join(empty))
else:
    ok.append("PROGRESS.md has an entry for every Project 3 session")

# 4. Git hygiene (the grader sees only what git tracks)
tracked = git("ls-files", "--full-name", ".")
if tracked is None:
    warnings.append("git is not available here, or this folder is not in a git repository.")
else:
    files = tracked.split()
    bad = [f for f in files if f.endswith((".duckdb", ".duckdb.wal", ".env", ".tmp"))
           or "/.venv/" in f or f.startswith(".venv/") or "/data/raw/" in f
           or (f.endswith(".parquet") and "/data/sample/" not in f)]
    (problems if bad else ok).append(
        ("git tracks files that must not be committed: " + ", ".join(bad[:8]) + (" ..." if len(bad) > 8 else ""))
        if bad else "git hygiene: no databases, raw data, .env or .venv tracked")
    for must in ["README.md", "producer.py", "lander.py", "flow.py", "SOURCE_CARD.md", "RUBRIC.md"]:
        if not any(f.endswith("project3/" + must) or f == must for f in files):
            problems.append(f"{must} is not committed (git add it)")
    if not any("/data/sample/" in f or f.startswith("data/sample/") for f in files):
        problems.append("data/sample/ is not committed (git add data/sample)")
    status = git("status", "--porcelain", ".")
    if status and status.strip():
        warnings.append("You have uncommitted changes: git add, commit and push before submitting.")
    remote = git("remote", "get-url", "origin") or ""
    if "ds3022-streaming" not in remote:
        warnings.append(f"origin points to '{remote.strip() or 'nothing'}', not your ds3022-streaming repo.")
    tags = git("tag", "--list", "dp3-submit") or ""
    if not tags.strip():
        warnings.append("No tag dp3-submit yet. Create it LAST: git tag dp3-submit && git push origin dp3-submit")
    else:
        ok.append("tag dp3-submit exists")

# Report
print("\nData Project 3 pre-submission check\n" + "-" * 36)
for line in ok:
    print("  OK    " + line)
for line in warnings:
    print("  WARN  " + line)
for line in problems:
    print("  FIX   " + line)
print()
if problems:
    print(f"NOT READY: {len(problems)} thing(s) to fix.")
    sys.exit(1)
print("READY" + (" (read the warnings above)" if warnings else ""))
